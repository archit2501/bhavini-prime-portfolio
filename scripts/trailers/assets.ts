/**
 * Prepares the HyperFrames trailer project's assets (task 1.3.3):
 *
 *   node scripts/trailers/assets.ts
 *
 * Copies each trailer title's generated key art at 1920x1080 and writes assets/titles.js, a
 * synchronous script that hands the composition its title lettering (SVG paths), the
 * "bhavini original" ident and the palette accents. Run `npm run art` first.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';
import { TITLES } from '../art/direction.ts';
import { TRAILER_TITLES } from './titles.ts';

const ROOT = new URL('../../', import.meta.url).pathname;
const OUT = `${ROOT}media/trailers/assets/`;

mkdirSync(`${OUT}fonts`, { recursive: true });
const titles: Record<string, unknown> = {};
for (const slug of TRAILER_TITLES) {
  const art = `${ROOT}src/assets/art/generated/${slug}/`;
  await sharp(`${art}key.jpg`)
    .resize(1920, 1080)
    .jpeg({ quality: 88, mozjpeg: true })
    .toFile(`${OUT}${slug}-key.jpg`);
  const logo = JSON.parse(readFileSync(`${art}logo.json`, 'utf8'));
  titles[slug] = { logo, accent: TITLES[slug].palette.accent, glow: TITLES[slug].palette.glows[0] };
}
const ident = JSON.parse(readFileSync(`${ROOT}src/assets/brand/ident.json`, 'utf8'));
writeFileSync(
  `${OUT}titles.js`,
  `// Generated by scripts/trailers/assets.ts. Do not edit by hand.\nwindow.__TRAILER = ${JSON.stringify({ ident, titles })};\n`,
);
copyFileSync(
  `${ROOT}node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2`,
  `${OUT}fonts/inter-latin-wght-normal.woff2`,
);
console.log(`trailer assets: ${TRAILER_TITLES.join(', ')}`);
